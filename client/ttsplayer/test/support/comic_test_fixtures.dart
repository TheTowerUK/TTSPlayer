/// Minimal 1×1 PNG bytes.
Uint8List tinyPng([int seed = 0]) {
  final bytes = base64DecodePng();
  bytes[bytes.length - 5] = (bytes[bytes.length - 5] + seed) % 256;
  return bytes;
}

Uint8List base64DecodePng() {
  return Uint8List.fromList(const [
    0x89, 0x50, 0x4E, 0x47, 0x0D, 0x0A, 0x1A, 0x0A, 0x00, 0x00, 0x00, 0x0D,
    0x49, 0x48, 0x44, 0x52, 0x00, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00, 0x01,
    0x08, 0x06, 0x00, 0x00, 0x00, 0x1F, 0x15, 0xC4, 0x89, 0x00, 0x00, 0x00,
    0x0A, 0x49, 0x44, 0x41, 0x54, 0x78, 0x9C, 0x63, 0x00, 0x01, 0x00, 0x00,
    0x05, 0x00, 0x01, 0x0D, 0x0A, 0x2D, 0xB4, 0x00, 0x00, 0x00, 0x00, 0x49,
    0x45, 0x4E, 0x44, 0xAE, 0x42, 0x60, 0x82,
  ]);
}

/// Writes a CBZ with the given entry name → bytes map.
File writeCbz(Directory dir, String name, Map<String, List<int>> entries) {
  final archive = Archive();
  for (final e in entries.entries) {
    archive.addFile(
      ArchiveFile(e.key, e.value.length, e.value),
    );
  }
  final encoded = ZipEncoder().encode(archive)!;
  final file = File('${dir.path}${Platform.pathSeparator}$name');
  file.writeAsBytesSync(encoded);
  return file;
}
